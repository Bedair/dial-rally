#!/usr/bin/env python3
"""Convert PNG sprites to RGB565 C++ headers for the M5Stack Dial.

For every assets/sprites/<name>.png this writes src/display/sprites/<name>.h
containing the pixels as RGB565 and a half-brightness copy (used to draw
obstacles faint while they are only a warning), plus Sprites.h which
includes them all.

Transparency: pixels with alpha < 128 become the colour key SPRITE_KEY
(magenta 0xF81F). An opaque pixel that happens to convert to the key is
nudged by one bit so it never turns transparent by accident.

    python tools/png2rgb565.py [png_dir] [header_dir]

Needs Pillow (pip install pillow).
"""
from pathlib import Path
import re
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
KEY = 0xF81F


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def convert(img, dim=False):
    img = img.convert("RGBA")
    out = []
    for r, g, b, a in img.getdata():
        if a < 128:
            out.append(KEY)
            continue
        if dim:
            r, g, b = r // 2, g // 2, b // 2
        v = rgb565(r, g, b)
        out.append(v ^ 1 if v == KEY else v)
    return out


def c_array(name, values, width):
    lines = []
    for i in range(0, len(values), width):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in values[i:i + width]) + ",")
    return f"constexpr uint16_t {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets" / "sprites"
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src" / "display" / "sprites"
    dst.mkdir(parents=True, exist_ok=True)

    names = []
    for png in sorted(src.glob("*.png")):
        name = re.sub(r"[^A-Za-z0-9]", "_", png.stem).upper()
        img = Image.open(png)
        w, h = img.size
        header = (
            f"// Generated by tools/png2rgb565.py from assets/sprites/{png.name}. Do not edit.\n"
            "#pragma once\n"
            '#include "display/Sprite.h"\n\n'
            "namespace spr {\n\n"
            + c_array(f"{name}_PX", convert(img), w) + "\n"
            + c_array(f"{name}_DIM", convert(img, dim=True), w) + "\n"
            + f"constexpr Sprite {name} = {{{name}_PX, {name}_DIM, {w}, {h}}};\n\n"
            "}  // namespace spr\n"
        )
        (dst / f"{png.stem}.h").write_text(header, newline="\n")
        names.append(png.stem)
        print(f"{png.name:16} {w:3}x{h:<3} -> {(dst / (png.stem + '.h')).relative_to(ROOT)}")

    index = (
        "// Generated by tools/png2rgb565.py. Do not edit.\n"
        "// Every sprite in assets/sprites/, as spr::<NAME> (see display/Sprite.h).\n"
        "#pragma once\n"
        + "".join(f'#include "display/sprites/{n}.h"\n' for n in names)
    )
    (dst / "Sprites.h").write_text(index, newline="\n")
    print(f"{len(names)} sprites, index: {(dst / 'Sprites.h').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
